"""Check claims/claims.json against the run records and render CLAIMS.md.

  python tools/verify_claims.py            # verify every quoted number, rewrite CLAIMS.md
  python tools/verify_claims.py --checks   # also run each claim's theory check and require exit code 0

Exits non-zero if a record is missing, a number has drifted from its record, or a check fails. Run it in CI so the
README, the paper tables and the interactive bench can never quote a number the records do not contain.
"""
from __future__ import annotations
import argparse, json, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
STATUSES = {"known", "checked", "exploratory", "fails", "untested"}


def lookup(data, ev):
    """Value of one evidence item: a row selected from a list of records, or a dotted path ('*' averages a list)."""
    if "select" in ev:
        rows = [r for r in data if all(r.get(k) == v for k, v in ev["select"].items())]
        if len(rows) != 1:
            raise KeyError(f"select {ev['select']} matched {len(rows)} rows")
        return float(rows[0][ev["field"]])
    nodes = [data]
    for part in ev["path"].split("."):
        nodes = [x for n in nodes for x in (n if part == "*" else [n[int(part)] if isinstance(n, list) else n[part]])]
    return float(sum(nodes) / len(nodes))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--checks", action="store_true", help="run each distinct check command of a theorem")
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args()
    ledger = json.loads((ROOT / "claims" / "claims.json").read_text())
    errors, lines, ran = [], [], {}
    for c in ledger["claims"]:
        if c["status"] not in STATUSES:
            errors.append(f"{c['id']}: unknown status {c['status']}")
        if c["status"] in ("exploratory", "fails") and not c["evidence"]:
            errors.append(f"{c['id']}: status {c['status']} needs at least one record")
        shown = []
        for ev in c["evidence"]:
            path = ROOT / ev["file"]
            if not path.exists():
                errors.append(f"{c['id']}: missing record {ev['file']}")
                continue
            try:
                got = lookup(json.loads(path.read_text()), ev)
            except (KeyError, IndexError, TypeError, ValueError) as exc:
                errors.append(f"{c['id']}: cannot read {ev['file']}: {exc}")
                continue
            if abs(got - ev["value"]) > ev["tol"]:
                errors.append(f"{c['id']}: {ev['label']} is {got:.4f} in {ev['file']}, ledger says {ev['value']}")
            shown.append(f"{ev['label']}: {got:.3f} (`{ev['file']}`)")
        if args.checks and c["kind"] == "theorem" and c["check"]:
            if c["check"] not in ran:
                ran[c["check"]] = subprocess.run(c["check"].split(), cwd=ROOT, capture_output=True).returncode
            if ran[c["check"]] != 0:
                errors.append(f"{c['id']}: check failed: {c['check']}")
        check = f"`{c['check']}`" if c["check"] else "none yet"
        lines.append(f"| {c['id']} | {c['status']} | {c['statement']} | {'<br>'.join(shown) or '-'} | {check} |")
    if not args.no_write:
        head = ["# Claims and evidence", "",
                f"Generated by `tools/verify_claims.py` from `claims/claims.json` (as of {ledger['as_of']}). Do not edit by hand.", "",
                "Status: **known** = prior result, cited, not claimed as new; **checked** = numerical check passes and a reference",
                "proof exists (AI-drafted; the author's own proof is pending); **exploratory** = few-seed runs, not pre-registered;",
                "**fails** = the stated test fails as written; **untested** = no evidence yet.", "",
                "| Claim | Status | Statement | Numbers, read from the records | Check |", "|---|---|---|---|---|"]
        (ROOT / "CLAIMS.md").write_text("\n".join(head + lines) + "\n")
    for e in errors:
        print("ERROR", e)
    print(f"{len(ledger['claims'])} claims, {sum(len(c['evidence']) for c in ledger['claims'])} numbers checked, "
          f"{len(ran)} check scripts run, {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
